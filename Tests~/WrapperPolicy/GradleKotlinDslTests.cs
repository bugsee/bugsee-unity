        [Test]
        public void Maven_central_with_a_content_block_counts_as_declared()
        {
            const string root =
                "allprojects {\n" +
                "    repositories {\n" +
                "        mavenCentral {\n" +
                "            content { includeGroup(\"com.bugsee\") }\n" +
                "        }\n" +
                "    }\n" +
                "}\n";

            Assert.That(
                GradleMavenInjection.EnsureMavenCentral(root, "allprojects", out string updated),
                Is.EqualTo(GradleMavenInjection.RepositoryStatus.AlreadyPresent));
            Assert.That(updated, Is.EqualTo(root));
        }

        [Test]
        public void Multi_line_triple_quoted_strings_do_not_hide_or_fake_structure()
        {
            const string gradle =
                "val notes = \"\"\"\n" +
                "dependencies {\n" +
                "    implementation(\"com.bugsee:bugsee-android:7.0.0\")\n" +
                "\"\"\"\n" +
                "\n" +
                "dependencies {\n" +
                "    implementation(fileTree(\"libs\"))\n" +
                "}\n";
            var result = ApplyKts(gradle);

            Assert.That(result.Status, Is.EqualTo(GradleMavenInjection.DependencyStatus.Injected));
            Assert.That(result.Text, Does.Contain("dependencies {\n    // bugsee:maven-dependencies begin"));
            Assert.That(result.Text.IndexOf("val notes"), Is.LessThan(result.Text.IndexOf("bugsee:maven-dependencies begin")));
            Assert.That(result.Text, Does.StartWith(gradle.Substring(0, gradle.IndexOf("dependencies {\n    implementation(fileTree"))));
        }
