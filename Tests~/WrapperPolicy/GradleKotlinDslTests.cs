                Is.EqualTo(GradleMavenInjection.RepositoriesMode.PreferProject));
            Assert.That(GradleMavenInjection.GetRepositoriesMode(
                    "dependencyResolutionManagement {\n    // repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)\n}\n"),
                Is.EqualTo(GradleMavenInjection.RepositoriesMode.Unspecified));
            Assert.That(GradleMavenInjection.GetRepositoriesMode("include ':a'\n"),
                Is.EqualTo(GradleMavenInjection.RepositoriesMode.Unspecified));
        }

