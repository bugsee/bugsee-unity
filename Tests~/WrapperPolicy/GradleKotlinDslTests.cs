        static GradleMavenInjection.DependencyResult ApplyGroovy(string gradle)
        {
            return GradleMavenInjection.ApplyDependencies(gradle, Group, Artifacts, Version);
        }

        [TestCase("    compileOnly 'com.bugsee:bugsee-android:7.4.1'")]
        [TestCase("    testImplementation 'com.bugsee:bugsee-android:7.4.1'")]
        [TestCase("    androidTestImplementation 'com.bugsee:bugsee-android-ndk:7.4.1'")]
        [TestCase("    implementation('com.example:lib:1') { exclude group: 'com.bugsee', module: 'bugsee-android' }")]
        [TestCase("    implementation('com.example:lib:1') {\n        exclude group: 'com.bugsee', module: 'bugsee-android'\n    }")]
        public void Groovy_other_configurations_and_exclusions_are_not_project_declarations(string line)
        {
            var result = ApplyGroovy("dependencies {\n" + line + "\n}\n");

            Assert.That(result.Status, Is.EqualTo(GradleMavenInjection.DependencyStatus.Injected));
            Assert.That(result.Warnings, Is.Empty);
        }

        [TestCase("    compileOnly(\"com.bugsee:bugsee-android:7.4.1\")")]
        [TestCase("    testImplementation(\"com.bugsee:bugsee-android:7.4.1\")")]
        [TestCase("    androidTestImplementation(\"com.bugsee:bugsee-android-ndk:7.4.1\")")]
        [TestCase("    implementation(\"com.example:lib:1\") { exclude(group = \"com.bugsee\", module = \"bugsee-android\") }")]
        [TestCase("    implementation(\"com.example:lib:1\") {\n        exclude(module = \"bugsee-android\")\n    }")]
        public void Kotlin_other_configurations_and_exclusions_are_not_project_declarations(string line)
        {
            var result = ApplyKts("dependencies {\n" + line + "\n}\n");

            Assert.That(result.Status, Is.EqualTo(GradleMavenInjection.DependencyStatus.Injected));
