using NUnit.Framework;

namespace Bugsee.WrapperPolicy.Tests
{
    /// <summary>
    /// Kotlin-DSL and repositories-mode handling of <see cref="GradleMavenInjection"/>.
    ///
    /// Fixture provenance: the 2021.3 settings fixture is the settingsTemplate.gradle shipped in Unity
    /// 2021.3.45f1 (PlaybackEngines/AndroidPlayer/Tools/GradleTemplates) with its placeholders emptied and mavenCentral() dropped from the project repositories (so there is something to insert). The
    /// Kotlin, 2022 and Unity 6 fixtures are RECONSTRUCTED (no 2022/6 editor was available): Unity 2022.2+ and
    /// Unity 6 keep the same Groovy settings shape (vendor docs show PREFER_SETTINGS + google/mavenCentral/flatDir),
    /// and Unity generates no .kts files itself, so the .kts fixtures model a project that converted them.
    /// </summary>
    public class GradleKotlinDslTests
    {
        const string Group = "com.bugsee";
        const string Version = "7.4.1";
        static readonly string[] Artifacts = { "bugsee-android", "bugsee-android-ndk" };

        const string KtsCore = "    implementation(\"com.bugsee:bugsee-android:7.4.1\")";
        const string KtsNdk = "    implementation(\"com.bugsee:bugsee-android-ndk:7.4.1\")";

        // 2021.3.45 settingsTemplate.gradle, placeholders emptied, project mavenCentral() removed.
        const string Unity2021Settings =
            "pluginManagement {\n" +
            "    repositories {\n" +
            "        \n" +
            "        gradlePluginPortal()\n" +
            "        google()\n" +
            "        mavenCentral()\n" +
            "    }\n" +
            "}\n" +
            "\n" +
            "include ':launcher', ':unityLibrary'\n" +
            "\n" +
            "\n" +
            "dependencyResolutionManagement {\n" +
            "    repositoriesMode.set(RepositoriesMode.PREFER_SETTINGS)\n" +
            "    repositories {\n" +
            "        \n" +
            "        google()\n" +
            "        flatDir {\n" +
            "            dirs \"${project(':unityLibrary').projectDir}/libs\"\n" +
            "        }\n" +
            "    }\n" +
            "}\n";

        // RECONSTRUCTED, not generated by Unity 6: the 2021.3.45 baseProjectTemplate.gradle with the AGP version
        // changed. Whether Unity 6's template differs beyond that could not be confirmed (docs describe the files'
        // roles, not their contents).
        const string ReconstructedRootBuild =
            "plugins {\n" +
            "    id 'com.android.application' version '8.3.0' apply false\n" +
            "    id 'com.android.library' version '8.3.0' apply false\n" +
            "}\n" +
            "\n" +
            "task clean(type: Delete) {\n" +
            "    delete rootProject.buildDir\n" +
            "}\n";

        const string KtsLibrary =
            "plugins {\n" +
            "    id(\"com.android.library\")\n" +
            "}\n" +
            "\n" +
            "dependencies {\n" +
            "    implementation(fileTree(mapOf(\"dir\" to \"libs\", \"include\" to listOf(\"*.jar\"))))\n" +
            "}\n" +
            "\n" +
            "android {\n" +
            "    namespace = \"com.unity3d.player\"\n" +
            "}\n";

        const string KtsSettings =
            "pluginManagement {\n" +
            "    repositories {\n" +
            "        gradlePluginPortal()\n" +
            "        google()\n" +
            "    }\n" +
            "}\n" +
            "\n" +
            "include(\":launcher\", \":unityLibrary\")\n" +
            "\n" +
            "dependencyResolutionManagement {\n" +
            "    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)\n" +
            "    repositories {\n" +
            "        google()\n" +
            "        flatDir {\n" +
            "            dirs(\"${project(\":unityLibrary\").projectDir}/libs\")\n" +
            "        }\n" +
            "    }\n" +
            "}\n";

        static GradleMavenInjection.DependencyResult ApplyKts(string gradle)
        {
            return GradleMavenInjection.ApplyDependencies(
                gradle, Group, Artifacts, Version, GradleMavenInjection.GradleDsl.Kotlin);
        }

        [Test]
        public void Dsl_is_chosen_by_file_name()
        {
            Assert.That(GradleMavenInjection.DslForFile("/p/unityLibrary/build.gradle.kts"),
                Is.EqualTo(GradleMavenInjection.GradleDsl.Kotlin));
            Assert.That(GradleMavenInjection.DslForFile("/p/unityLibrary/build.gradle"),
                Is.EqualTo(GradleMavenInjection.GradleDsl.Groovy));
        }

        [Test]
        public void Kotlin_library_gets_function_call_declarations_and_is_idempotent()
        {
            var first = ApplyKts(KtsLibrary);

            Assert.That(first.Status, Is.EqualTo(GradleMavenInjection.DependencyStatus.Injected));
            Assert.That(first.Text, Does.Contain(KtsCore + "\n" + KtsNdk + "\n"));
            Assert.That(first.Text, Does.Not.Contain("implementation 'com.bugsee"));
            Assert.That(first.Text.IndexOf("dependencies {"), Is.LessThan(first.Text.IndexOf(KtsCore)));
            Assert.That(first.Text.IndexOf(KtsCore), Is.LessThan(first.Text.IndexOf("android {")));

            var second = ApplyKts(first.Text);
            Assert.That(second.Status, Is.EqualTo(GradleMavenInjection.DependencyStatus.AlreadyInjected));
            Assert.That(second.Text, Is.EqualTo(first.Text));
        }

        [Test]
        public void Kotlin_project_declarations_are_recognised_and_kept()
        {
            string gradle = KtsLibrary.Replace(
                "dependencies {\n",
                "dependencies {\n    implementation(\"com.bugsee:bugsee-android:7.3.0\")\n    implementation(\"com.bugsee:bugsee-android-ndk:7.3.0\")\n");
            var result = ApplyKts(gradle);

            Assert.That(result.Status, Is.EqualTo(GradleMavenInjection.DependencyStatus.DeclaredByProject));
            Assert.That(result.Text, Is.EqualTo(gradle));
            Assert.That(result.Warnings, Has.Count.EqualTo(2));
        }

        [Test]
        public void Version_catalog_alias_is_not_seen_as_a_declaration_and_is_not_duplicated()
        {
            // libs.bugsee.android carries no coordinate text, so the injector cannot know; it adds the pinned one.
            string gradle = KtsLibrary.Replace("dependencies {\n", "dependencies {\n    implementation(libs.bugsee.android)\n");
            var result = ApplyKts(gradle);

            Assert.That(result.Status, Is.EqualTo(GradleMavenInjection.DependencyStatus.Injected));
        }

        [Test]
        public void Kotlin_file_without_a_dependencies_block_gets_one()
        {
            string gradle = "plugins {\n    id(\"com.android.library\")\n}\n";
            var result = ApplyKts(gradle);

            Assert.That(result.Text, Does.EndWith("dependencies {\n" +
                "    // bugsee:maven-dependencies begin (com.bugsee.unity)\n" +
                KtsCore + "\n" + KtsNdk + "\n" +
                "    // bugsee:maven-dependencies end\n}\n"));
        }

        [Test]
        public void Groovy_overload_keeps_the_groovy_syntax()
        {
            var result = GradleMavenInjection.ApplyDependencies(
                "dependencies {\n}\n", Group, Artifacts, Version);

            Assert.That(result.Text, Does.Contain("implementation 'com.bugsee:bugsee-android:7.4.1'"));
        }

        [Test]
        public void Repositories_mode_is_read_from_the_settings_block()
        {
            Assert.That(GradleMavenInjection.GetRepositoriesMode(Unity2021Settings),
                Is.EqualTo(GradleMavenInjection.RepositoriesMode.PreferSettings));
            Assert.That(GradleMavenInjection.GetRepositoriesMode(KtsSettings),
                Is.EqualTo(GradleMavenInjection.RepositoriesMode.FailOnProjectRepos));
            Assert.That(GradleMavenInjection.GetRepositoriesMode(
                    "dependencyResolutionManagement {\n    repositoriesMode = RepositoriesMode.PREFER_PROJECT\n}\n"),
                Is.EqualTo(GradleMavenInjection.RepositoriesMode.PreferProject));
            Assert.That(GradleMavenInjection.GetRepositoriesMode(
                    "dependencyResolutionManagement {\n    // repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)\n}\n"),
                Is.EqualTo(GradleMavenInjection.RepositoriesMode.Unspecified));
            Assert.That(GradleMavenInjection.GetRepositoriesMode("include ':a'\n"),
                Is.EqualTo(GradleMavenInjection.RepositoriesMode.Unspecified));
        }

        [Test]
        public void Unity_2021_settings_without_maven_central_get_it_in_settings_only()
        {
            var result = GradleMavenInjection.EnsureProjectRepositories(Unity2021Settings, ReconstructedRootBuild);

            Assert.That(result.SettingsStatus, Is.EqualTo(GradleMavenInjection.RepositoryStatus.Inserted));
            Assert.That(result.RootBuildStatus, Is.EqualTo(GradleMavenInjection.RepositoryStatus.BlockNotFound));
            Assert.That(result.Found, Is.True);
            Assert.That(result.RootBuild, Is.EqualTo(ReconstructedRootBuild));

            var again = GradleMavenInjection.EnsureProjectRepositories(result.Settings, result.RootBuild);
            Assert.That(again.SettingsStatus, Is.EqualTo(GradleMavenInjection.RepositoryStatus.AlreadyPresent));
            Assert.That(again.Settings, Is.EqualTo(result.Settings));
        }

        [Test]
        public void Kotlin_settings_with_fail_on_project_repos_get_it_in_settings_and_never_in_the_root()
        {
            const string rootKts =
                "allprojects {\n" +
                "    repositories {\n" +
                "        google()\n" +
                "    }\n" +
                "}\n";
            var result = GradleMavenInjection.EnsureProjectRepositories(KtsSettings, rootKts);

            Assert.That(result.Mode, Is.EqualTo(GradleMavenInjection.RepositoriesMode.FailOnProjectRepos));
            Assert.That(result.SettingsStatus, Is.EqualTo(GradleMavenInjection.RepositoryStatus.Inserted));
            Assert.That(result.Settings, Does.Contain("    repositories {\n        mavenCentral() // bugsee:maven-repository\n        google()"));
            Assert.That(result.RootBuild, Is.EqualTo(rootKts));
        }

        [Test]
        public void Fail_on_project_repos_without_settings_repositories_is_never_given_root_repositories()
        {
            const string settings =
                "dependencyResolutionManagement {\n" +
                "    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)\n" +
                "}\n";
            var result = GradleMavenInjection.EnsureProjectRepositories(
                settings, "allprojects {\n    repositories {\n        google()\n    }\n}\n");

            Assert.That(result.SettingsStatus, Is.EqualTo(GradleMavenInjection.RepositoryStatus.Inserted));
            Assert.That(result.RootBuildStatus, Is.EqualTo(GradleMavenInjection.RepositoryStatus.BlockNotFound));
        }

        [Test]
        public void Prefer_project_keeps_the_root_allprojects_repositories_in_step()
        {
            string settings = Unity2021Settings.Replace("PREFER_SETTINGS", "PREFER_PROJECT");
            const string root =
                "allprojects {\n" +
                "    repositories {\n" +
                "        google()\n" +
                "    }\n" +
                "}\n";
            var result = GradleMavenInjection.EnsureProjectRepositories(settings, root);

            Assert.That(result.SettingsStatus, Is.EqualTo(GradleMavenInjection.RepositoryStatus.Inserted));
            Assert.That(result.RootBuildStatus, Is.EqualTo(GradleMavenInjection.RepositoryStatus.Inserted));
            Assert.That(result.RootBuild, Does.Contain("mavenCentral() // bugsee:maven-repository"));
        }

        [Test]
        public void Settings_without_the_block_fall_back_to_the_root_allprojects()
        {
            const string root =
                "allprojects {\n" +
                "    repositories {\n" +
                "        google()\n" +
                "    }\n" +
                "}\n";
            var result = GradleMavenInjection.EnsureProjectRepositories("include ':launcher'\n", root);

            Assert.That(result.SettingsStatus, Is.EqualTo(GradleMavenInjection.RepositoryStatus.BlockNotFound));
            Assert.That(result.RootBuildStatus, Is.EqualTo(GradleMavenInjection.RepositoryStatus.Inserted));
