#!/usr/bin/env bash
# Regenerates the Android SDK API snapshot that Tests~/WrapperPolicy/AndroidSdkBindingTests.cs checks the JNI calls
# in Runtime/Platform/Android/*.cs against: the public signatures (javap -public) of com.bugsee.library.Bugsee and
# every com.bugsee.library.contracts class (the API the wrapper is written against; internals are left out) in the pinned bugsee-android and bugsee-android-feedback artifacts (Tools~/versions.env).
#
#   Tools~/scripts/update-android-api-manifest.sh            # download the pinned AARs from Maven Central
#   BUGSEE_ANDROID_AAR_DIR=dir Tools~/scripts/update-android-api-manifest.sh   # use dir/<artifact>-<version>.aar
#
# Run it after Tools~/scripts/update-native-sdks.sh moves the Android pin; the test fails until the snapshot's
# version matches the pin. Needs a JDK (javap), curl and unzip.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# shellcheck disable=SC1091
source "${ROOT_DIR}/Tools~/versions.env"

OUT_DIR="${ROOT_DIR}/Tests~/WrapperPolicy/Fixtures/android-sdk-api"
OUT="${OUT_DIR}/${ANDROID_SDK_VERSION}.txt"
WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

command -v javap >/dev/null || { echo "javap (a JDK) is required" >&2; exit 1; }
# Built in the work directory; the committed snapshot is replaced only once everything succeeded.
NEW="${WORK}/snapshot.txt"
{
  echo "# Public API of com.bugsee.library.Bugsee and com.bugsee.library.contracts.** in ${ANDROID_MAVEN_ARTIFACT} and ${ANDROID_FEEDBACK_ARTIFACT} ${ANDROID_SDK_VERSION} (javap -public)."
  echo "# Generated by Tools~/scripts/update-android-api-manifest.sh with $(javap -version 2>&1 | head -n 1). Do not edit."
} > "${NEW}"

for ARTIFACT in "${ANDROID_MAVEN_ARTIFACT}" "${ANDROID_FEEDBACK_ARTIFACT}"; do
  AAR="${WORK}/${ARTIFACT}.aar"
  if [[ -n "${BUGSEE_ANDROID_AAR_DIR:-}" ]]; then
    cp "${BUGSEE_ANDROID_AAR_DIR}/${ARTIFACT}-${ANDROID_SDK_VERSION}.aar" "${AAR}"
  else
    curl -fsSL -o "${AAR}" \
      "https://repo1.maven.org/maven2/${ANDROID_MAVEN_GROUP//.//}/${ARTIFACT}/${ANDROID_SDK_VERSION}/${ARTIFACT}-${ANDROID_SDK_VERSION}.aar"
  fi
  unzip -q -o "${AAR}" classes.jar -d "${WORK}/${ARTIFACT}"
  JAR="${WORK}/${ARTIFACT}/classes.jar"
  # Named classes only (anonymous and synthetic ones end in $<digits>); sorted so a regeneration diffs cleanly.
  CLASSES=$(unzip -Z1 "${JAR}" | grep -E '^com/bugsee/library/(Bugsee(\$.*)?|contracts/.*)\.class$' | grep -Ev '\$[0-9]+\.class$' \
    | sed -e 's#\.class$##' -e 's#/#.#g' | LC_ALL=C sort)
  # shellcheck disable=SC2086
  javap -public -cp "${JAR}" ${CLASSES} | grep -v '^Compiled from' >> "${NEW}"
done

[[ $(grep -c "^public" "${NEW}") -gt 100 ]] || { echo "snapshot looks empty; keeping the old one" >&2; exit 1; }
mkdir -p "${OUT_DIR}"
rm -f "${OUT_DIR}"/*.txt
cp "${NEW}" "${OUT}"
echo "Wrote ${OUT} ($(wc -l < "${OUT}" | tr -d ' ') lines)"
